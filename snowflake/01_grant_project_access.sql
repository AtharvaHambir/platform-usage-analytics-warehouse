-- Run once in a Snowsight SQL worksheet under ACCOUNTADMIN.
-- Creates a dedicated service user for the local dbt project.
-- Replace <PASTE_BASE64_PUBLIC_KEY> with your own user's public key.
-- Never put the matching private key in this file or a Git repository.
USE ROLE ACCOUNTADMIN;

CREATE ROLE PLATFORM_USAGE_DBT_ROLE;
GRANT ROLE PLATFORM_USAGE_DBT_ROLE TO ROLE SYSADMIN;

CREATE DATABASE PLATFORM_USAGE_LAB;
CREATE SCHEMA PLATFORM_USAGE_LAB.LANDING;
CREATE SCHEMA PLATFORM_USAGE_LAB.ANALYTICS;

CREATE WAREHOUSE PLATFORM_USAGE_XS
    WAREHOUSE_SIZE = 'XSMALL'
    INITIALLY_SUSPENDED = TRUE
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    STATEMENT_TIMEOUT_IN_SECONDS = 300;

GRANT USAGE ON WAREHOUSE PLATFORM_USAGE_XS TO ROLE PLATFORM_USAGE_DBT_ROLE;
GRANT USAGE ON DATABASE PLATFORM_USAGE_LAB TO ROLE PLATFORM_USAGE_DBT_ROLE;
GRANT USAGE, CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT
    ON SCHEMA PLATFORM_USAGE_LAB.LANDING TO ROLE PLATFORM_USAGE_DBT_ROLE;
GRANT USAGE, CREATE TABLE, CREATE VIEW
    ON SCHEMA PLATFORM_USAGE_LAB.ANALYTICS TO ROLE PLATFORM_USAGE_DBT_ROLE;

CREATE USER PLATFORM_USAGE_DBT_USER
    TYPE = SERVICE
    RSA_PUBLIC_KEY = '<PASTE_BASE64_PUBLIC_KEY>'
    DEFAULT_ROLE = PLATFORM_USAGE_DBT_ROLE
    DEFAULT_WAREHOUSE = PLATFORM_USAGE_XS;
GRANT ROLE PLATFORM_USAGE_DBT_ROLE TO USER PLATFORM_USAGE_DBT_USER;

SHOW GRANTS TO USER PLATFORM_USAGE_DBT_USER;
